"""Collect the metrics written by the notebooks into results/RESULTS.md.

Usage: unzip each results_<module>.zip from Drive into results/<module>/, then
    python tools/collect_results.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "results"


def load(p):
    p = R / p
    return json.loads(p.read_text()) if p.exists() else None


def pct(x):
    return f"{100 * x:.1f}" if isinstance(x, (int, float)) else "–"


def seg_rows(module, label, test_files, baselines_key=None):
    rows = []
    for name, f in test_files.items():
        rep = load(f"{module}/{f}")
        if not rep:
            continue
        for split in [k for k in rep if k not in ("threshold",)]:
            m = rep[split]["at_chosen_threshold"]
            rows.append(f"| {label} | {name} | {split} | {pct(m['iou'])} | {pct(m['f1'])} | {pct(m['precision'])} | {pct(m['recall'])} |")
    bl = load(f"{module}/baselines.json")
    if bl:
        for bname, b in bl.items():
            for split in [k for k in b if k not in ("direction", "threshold", "val")]:
                m = b[split]
                rows.append(f"| {label} | baseline: {bname} | {split} | {pct(m['iou'])} | {pct(m['f1'])} | {pct(m['precision'])} | {pct(m['recall'])} |")
    return rows


def main():
    out = ["# Results", "", "Generated by `tools/collect_results.py` from the JSON files in this folder. "
           "All numbers are on held-out test data; thresholds were chosen on validation data.", ""]
    out += ["## Segmentation models (% , positive class)", "",
            "| Module | Model | Test split | IoU | F1 | Precision | Recall |", "|---|---|---|---|---|---|---|"]
    rows = []
    rows += seg_rows("floods", "Floods", {"U-Net S2": "test_flood_s2.json", "U-Net S1": "test_flood_s1.json",
                                          "U-Net S1+S2": "test_flood_s1s2.json"})
    rows += seg_rows("wildfires", "Wildfires", {"U-Net": "test_burn_scar.json"})
    rows += seg_rows("forestry", "Forestry", {"U-Net": "test_forest.json"})
    out += rows or ["| _pending first training run_ | | | | | | |"]

    out += ["", "## Agriculture — land-use classification", ""]
    lu = load("agriculture/test_landuse.json")
    if lu:
        out += [f"Test accuracy **{pct(lu['accuracy'])} %**, macro-F1 **{pct(lu['macro_f1'])} %** on {lu.get('n_images', '?')} images.", "",
                "| Class | Precision | Recall | F1 |", "|---|---|---|---|"]
        out += [f"| {c} | {pct(v['precision'])} | {pct(v['recall'])} | {pct(v['f1'])} |" for c, v in lu["per_class"].items()]
    else:
        out.append("_pending first training run_")

    out += ["", "## Air quality — next-day forecast, test year Oct 2025 – Sep 2026", ""]
    aq = load("air_quality/test_metrics.json")
    if aq:
        out += ["| Setting | LightGBM MAE | Persistence MAE | Skill vs persistence | R² |", "|---|---|---|---|---|"]
        for tag, r in aq.items():
            out.append(f"| {tag} | {r['LightGBM']['mae']:.2f} | {r['persistence']['mae']:.2f} | "
                       f"{100 * r['skill_vs_persistence_mae']:+.1f} % | {r['LightGBM']['r2']:.3f} |")
    else:
        out.append("_pending first training run_")

    (R / "RESULTS.md").write_text("\n".join(out) + "\n")
    print("wrote", R / "RESULTS.md")


if __name__ == "__main__":
    main()
